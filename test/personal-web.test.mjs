import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApplication } from '../src/application.mjs';
import { startServer } from '../src/server.mjs';

test('列表和详情提供即时保存复选框，GET入口不投递，HTTP操作持久保留关注与投递纠正', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'job-hunter-personal-web-'));
  const app = createApplication({ databasePath: join(directory, 'jobs.sqlite'), now: () => new Date('2026-10-07T02:00:00.000Z') });
  const job = app.createJob({ title: '算法专家', originalText: '模拟可核对原文', applicationPath: { kind: 'direct', url: 'https://example.org/job/1' } });
  const server = await startServer({ app, port: 0 });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); app.close(); rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, body) => {
    const response = await fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal(response.status, 200);
    return response.json();
  };
  const list = await (await fetch(base + '/jobs')).text();
  assert.match(list, /type="checkbox"[^>]*data-action="applied"/);
  const detail = await (await fetch(base + `/jobs/${job.id}`)).text();
  assert.match(detail, /type="checkbox"[^>]*data-action="applied"/);
  assert.match(detail, /href="https:\/\/example.org\/job\/1"/);
  assert.equal(app.getPersonalState(job.id).applied, false);
  const script = await fetch(base + '/assets/personal.js');
  assert.equal(script.status, 200);
  await post(`/api/jobs/${job.id}/personal`, { followed: true });
  const result = await post(`/api/jobs/${job.id}/applied`, { applied: true });
  assert.equal(result.personal.followed, true);
  assert.equal(result.personal.applied, true);
  const refreshed = await (await fetch(base + `/jobs/${job.id}`)).text();
  assert.match(refreshed, /data-action="applied"[^>]*checked/);
  await post(`/api/applications/${result.application.id}`, { appliedAt: '2026-10-06T03:00:00.000Z', notes: '实际提交', resumeVersion: '本人所用简历v1' });
  await post(`/api/applications/${result.application.id}/events`, { type: 'interview', note: '本人记录' });
  await post(`/api/jobs/${job.id}/applied`, { applied: false });
  const applications = await (await fetch(base + '/api/applications')).json();
  assert.equal(applications[0].corrected, true);
  assert.equal(applications[0].events.filter(event => event.type === 'interview').length, 1);
  assert.doesNotMatch(await (await fetch(base + '/applications')).text(), /算法专家/);
  assert.deepEqual(await (await fetch(base + '/api/applied-jobs')).json(), []);
  assert.match(await (await fetch(base + `/jobs/${job.id}`)).text(), /撤销误勾/);
});

test('Web后补备注保存北京时区与毫秒原时间，纠正历史在重启后仍可读', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'job-hunter-personal-form-'));
  const options = { databasePath: join(directory, 'jobs.sqlite'), now: () => new Date('2026-10-07T02:03:04.123Z') };
  const app = createApplication(options);
  const job = app.createJob({ title: '专家', originalText: '示例原文' });
  const application = app.setApplied(job.id, true);
  const server = await startServer({ app, port: 0 });
  let closed = false;
  t.after(async () => { if (!closed) { await new Promise(resolve => server.close(resolve)); app.close(); } rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const detail = await (await fetch(base + `/jobs/${job.id}`)).text();
  assert.match(detail, /value="2026-10-07T10:03:04.123"/);
  const response = await fetch(base + `/applications/${application.id}`, { method: 'POST', body: new URLSearchParams({ appliedAt: '2026-10-07T10:03:04.123', notes: '后补备注', resumeVersion: '' }), redirect: 'manual' });
  assert.equal(response.status, 303);
  assert.equal(app.getApplication(application.id).appliedAt, '2026-10-07T02:03:04.123Z');
  app.recordApplicationEvent(application.id, { type: 'interview', note: '面试已确认' });
  app.setApplied(job.id, false);
  await new Promise(resolve => server.close(resolve)); app.close(); closed = true;
  const restarted = createApplication(options);
  t.after(() => restarted.close());
  assert.equal(restarted.getApplication(application.id).notes, '后补备注');
  assert.equal(restarted.getApplication(application.id).events.filter(event => event.type === 'interview').length, 1);
  assert.equal(restarted.getApplication(application.id).events.filter(event => event.type === 'correction').length, 1);
});
